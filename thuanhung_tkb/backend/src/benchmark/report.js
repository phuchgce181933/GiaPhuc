// PHASE 31 — MARKDOWN REPORT RENDERER.
//
// Brief §34 lists the required sections. This module emits exactly
// them, in that order, and nothing else. It is a pure function of a
// benchmark result: the same result always renders the same report.
//
// THE ONE RULE THAT SHAPES THE OUTPUT
// -----------------------------------
// A report must be readable by someone who did not run it, and it must
// not make a claim its data does not carry. Concretely:
//
//   - a BLOCKED run prints `AIRLLM_BENCHMARK_BLOCKED` and says what
//     blocked it. It never prints a quality comparison it did not
//     make, and `n/a` is a legitimate cell value.
//   - a value the service did not report prints as `not reported`,
//     never as `unknown` or `latest` (brief §8).
//   - every distribution prints its per-run values, so a reader can
//     see the alternation a median hides (brief §23).
//   - the conclusion is printed verbatim from the result. The renderer
//     cannot upgrade it, and it is not allowed to fill in a missing
//     conclusion with a hopeful default.

import {
  ALL_AIRLLM_FAILURES,
} from './classification.js';
import { QUALITY_METRIC_NAMES, LATENCY_METRIC_NAMES } from './metrics.js';
import { ALLOWED_CONCLUSIONS, AI_STRATEGY_EVALUATION_POLICY } from './versions.js';
import { RUNTIME_RESULT } from './smoke.js';
import { BENCHMARK_ARMS } from './quality.js';

/**
 * renderBenchmarkReport(result) -> markdown string
 *
 *   result = {
 *     smoke:   TierA | null,
 *     quality: TierB | null,
 *     provenance: {...} | null,
 *     notes: string[],
 *   }
 */
export function renderBenchmarkReport(result = {}) {
  const { smoke = null, quality = null, provenance = null, notes = [] } = result;
  const out = [];

  out.push('# Phase 31 — Real AirLLM Smoke Test + AI Strategy Quality Benchmark');
  out.push('');
  out.push('> Generated by `src/benchmark/report.js` from a live benchmark run. Every number below');
  out.push('> is a measurement. Nothing in this file is a target, an expectation, or a projection.');
  out.push('');

  // ---- VERDICT, FIRST ---------------------------------------------
  out.push('## Verdict');
  out.push('');
  out.push(...verdictBlock(smoke, quality));
  out.push('');

  // ---- 0. How this benchmark works ---------------------------------
  // Methodology lives in the same file as the numbers, so the artifact
  // is self-contained: a reader who has only this document can tell
  // what was measured, what was held constant, and what the report is
  // not allowed to claim.
  out.push('## How this benchmark works');
  out.push('');
  out.push(...methodBlock(quality));
  out.push('');

  // ---- 1. Environment ---------------------------------------------
  out.push('## Environment');
  out.push('');
  out.push(...environmentBlock(smoke));
  out.push('');

  // ---- 2. Model ----------------------------------------------------
  out.push('## Model');
  out.push('');
  out.push(...modelBlock(smoke));
  out.push('');

  // ---- 3. AirLLM version -------------------------------------------
  out.push('## AirLLM version');
  out.push('');
  out.push(...airllmVersionBlock(smoke));
  out.push('');

  // ---- 4. Hardware --------------------------------------------------
  out.push('## Hardware');
  out.push('');
  out.push(...hardwareBlock(smoke));
  out.push('');

  // ---- 5. Dataset ---------------------------------------------------
  out.push('## Dataset');
  out.push('');
  out.push(...datasetBlock(provenance));
  out.push('');

  // ---- 6. Prompt version --------------------------------------------
  out.push('## Prompt version');
  out.push('');
  out.push(...promptBlock(smoke, quality));
  out.push('');

  // ---- 7. Runtime results -------------------------------------------
  out.push('## Runtime results (Tier A)');
  out.push('');
  out.push(...runtimeBlock(smoke));
  out.push('');

  // ---- 8. Strategy validity -----------------------------------------
  out.push('## Strategy validity');
  out.push('');
  out.push(...validityBlock(quality));
  out.push('');

  // ---- 9. Fallback rate ----------------------------------------------
  out.push('## Fallback rate');
  out.push('');
  out.push(...fallbackBlock(quality));
  out.push('');

  // ---- 10. Baseline results -----------------------------------------
  out.push('## Baseline results (DETERMINISTIC_FALLBACK)');
  out.push('');
  out.push(...armBlock(quality, BENCHMARK_ARMS.BASELINE));
  out.push('');

  // ---- 11. AirLLM results -------------------------------------------
  out.push('## AirLLM results');
  out.push('');
  out.push(...armBlock(quality, BENCHMARK_ARMS.AI));
  out.push('');

  // ---- 12. Quality comparison ---------------------------------------
  out.push('## Quality comparison');
  out.push('');
  out.push(...comparisonBlock(quality));
  out.push('');

  // ---- 13. Latency comparison ---------------------------------------
  out.push('## Latency comparison');
  out.push('');
  out.push(...latencyBlock(quality));
  out.push('');

  // ---- 14. Failure analysis ------------------------------------------
  out.push('## Failure analysis');
  out.push('');
  out.push(...failureBlock(quality));
  out.push('');

  // ---- 15. Conclusion -------------------------------------------------
  out.push('## Conclusion');
  out.push('');
  out.push(...conclusionBlock(quality));
  out.push('');

  if (notes.length > 0) {
    out.push('## Notes');
    out.push('');
    for (const n of notes) out.push(`- ${n}`);
    out.push('');
  }

  return out.join('\n');
}

