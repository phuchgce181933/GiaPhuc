/**
 * The method, in the same file as the results.
 *
 * Kept short on purpose. A methodology section that has to be
 * regenerated to stay in sync with the code is a section that will
 * eventually lie; this one describes invariants that are enforced in
 * `src/benchmark/runner.js` and asserted in
 * `tests/phase31_ai_strategy_benchmark.test.js`, and it says so.
 */
function methodBlock(quality) {
  const p = AI_STRATEGY_EVALUATION_POLICY;
  const lines = [];

  lines.push('Two questions, kept apart on purpose:');
  lines.push('');
  lines.push('1. **Tier A — does the AirLLM service work?** Health, readiness, and one `/plan` call');
  lines.push('   whose decision the Node validator accepts. It establishes a runtime, nothing else.');
  lines.push('2. **Tier B — is the AirLLM strategy useful?** The deterministic fallback and AirLLM');
  lines.push('   are compared on one fixed SchedulingInput.');
  lines.push('');
  lines.push('A Tier A PASS is not evidence for Tier B, and neither is reported as the other.');
  lines.push('');

  lines.push('### What is held constant (and how you can check)');
  lines.push('');
  lines.push('| Held constant | Where it is enforced |');
  lines.push('|---|---|');
  lines.push('| SchedulingInput | `benchmarkInputHash` over a personal-data-free structural projection; the input is never mutated between runs |');
  lines.push('| solver seed, per-solve and overall time budgets, `respectStrategyMode`, `requireFeasibility` | one frozen `BENCHMARK_SOLVER_PROFILE`; every run records the options it received, and both arms\' records are compared for equality |');
  lines.push('| candidate count | the MAXIMUM any arm asked for, decided before any solve |');
  lines.push('| solver implementation, independent evaluator, Phase 28 scorer | the same functions production calls; the benchmark reads their output and computes no opinion of its own |');
  lines.push('');

  lines.push('### What the AI is allowed to do');
  lines.push('');
  lines.push('Strategy selection, weight suggestion, candidate count, rationale. Nothing else. It cannot');
  lines.push('name a teacher, a class, a day, a period, a branch, or a slot: the decision vocabulary is a');
  lines.push('closed set, and a field the validator does not recognise is a rejection of the whole');
  lines.push('decision rather than a silent no-op. A decision that fails validation falls back, and the');
  lines.push('fallback run is never scored as if it were an AI run.');
  lines.push('');

  lines.push('### How the conclusion is reached');
  lines.push('');
  lines.push(`Policy \`${p.version}\`, decided on \`${p.primaryMetric}\` alone, aggregated by ${p.aggregator},`);
  lines.push(`epsilon \`${p.epsilon}\`. Validity gates the verdict. When the two arms\' ranges overlap, a`);
  lines.push('BETTER or WORSE verdict describes the median only and the conclusion is downgraded.');
  lines.push('');
  lines.push('Two yardsticks are computed and both are shown: the per-run pool-relative score the policy');
  lines.push('decides on, and a shared-pool score that puts both arms\' shipped schedules on one common');
  lines.push('scale. If they contradict, no direction is claimed.');
  lines.push('');
  lines.push('Only these five conclusions are reachable, and the renderer refuses to print any other:');
  lines.push('');
  for (const c of ALLOWED_CONCLUSIONS) lines.push(`- \`${c}\``);
  lines.push('');
  lines.push('A measurement that could not be taken is reported as not taken. Nothing here is retried');
  lines.push('until the numbers look better, and no run is selected out of the set.');
  return lines;
}

function verdictBlock(smoke, quality) {
  const lines = [];
  const runtime = smoke ? smoke.result : 'NOT RUN';
  lines.push('| Tier | Question | Answer |');
  lines.push('|---|---|---|');
  lines.push(`| A — runtime | does the AirLLM service work? | **${runtime}** |`);
  lines.push('| B — quality | is the AirLLM strategy useful? | **not collapsed into a single "AI = PASS"** |');
  lines.push('');
  if (quality) {
    lines.push(`**Conclusion: \`${quality.conclusion}\`**`);
    lines.push('');
    lines.push(quality.conclusionReason);
  } else {
    lines.push('**Conclusion: `AIRLLM_BENCHMARK_BLOCKED`** — Tier B was not run, so no quality claim is made.');
  }
  return lines;
}

function environmentBlock(smoke) {
  const env = smoke?.environment ?? null;
  // The Node host is always known, so it is always reported — it is
  // the AI service's environment that may be unobservable, and
  // printing "not reported" for the Node version would be a way of
  // making a knowable fact look unknown.
  const lines = kvTable([
    ['Node', process.version],
    ['Node platform', `${process.platform} ${process.arch}`],
    ['Node pid', String(process.pid)],
    ['AI service platform', env ? (env.platform ?? 'not reported') : 'not reported'],
    ['Model metadata complete', env ? yesNo(env.metadataComplete) : 'no'],
  ]);
  lines.push('');
  if (!env) {
    lines.push('No AirLLM service answered, so nothing about the AI runtime is reported. The values');
    lines.push('above are the Node host only.');
  }
  return lines;
}

function modelBlock(smoke) {
  const env = smoke?.environment ?? null;
  if (!env) return ['**not reported** — no service answered. `AIRLLM_RUNTIME_READY` was not established.', ''];
  const lines = kvTable([
    ['modelIdentifier', env.modelIdentifier],
    ['Model source', env.modelSource],
    ['Resolves locally', yesNo(env.modelResolvesLocally)],
    ['Remote code allowed', yesNo(env.allowRemoteCode)],
    ['Remote code used', yesNo(env.remoteCodeUsed)],
    ['Model loaded', yesNo(env.modelLoaded)],
    ['Service state', env.serviceState],
  ]);
  lines.push('');
  const instruct = smoke.instruct;
  lines.push(`**Instruct model requirement:** \`${instruct?.status ?? 'UNVERIFIED'}\``);
  lines.push('');
  lines.push(instruct?.note ?? '');
  return lines;
}

function airllmVersionBlock(smoke) {
  const env = smoke?.environment ?? null;
  if (!env) {
    return [
      '**not reported** — `airllmVersion`, `torchVersion`, and `transformersVersion` are `null` because no',
      'service answered. They are deliberately NOT written as `unknown` or `latest` (brief §8).',
      '',
    ];
  }
  return kvTable([
    ['airllmVersion', env.airllmVersion],
    ['torchVersion', env.torchVersion],
    ['transformersVersion', env.transformersVersion],
    ['fastapiVersion', env.fastapiVersion],
    ['pythonVersion', env.pythonVersion],
  ]);
}

function hardwareBlock(smoke) {
  const env = smoke?.environment ?? null;
  if (!env) return ['**not reported** — no service answered.', ''];
  return kvTable([
    ['device', env.device],
    ['cudaAvailable', env.cudaAvailable === null ? 'not reported' : yesNo(env.cudaAvailable)],
    ['dtype', env.dtype],
  ]);
}

function datasetBlock(provenance) {
  if (!provenance) return ['**not recorded** — the benchmark was invoked without provenance.', ''];
  const e = provenance.effective ?? {};
  const inv = provenance.inventory ?? {};
  const lines = kvTable([
    ['Source', provenance.source],
    ['benchmarkInputHash', provenance.benchmarkInputHash],
    ['datasetShapeHash', provenance.datasetShapeHash],
    ['dimensionCatalogVersion', provenance.dimensionCatalogVersion],
    ['scoringDefaultsVersion', provenance.scoringDefaultsVersion],
    ['legacyServerVersion', provenance.legacyServerVersion],
    ['legacyToolVersion', provenance.legacyToolVersion],
  ]);
  lines.push('');
  lines.push('| Collection | Count |');
  lines.push('|---|---|');
  for (const [k, v] of Object.entries(e)) lines.push(`| ${k} | ${v} |`);
  lines.push('');
  lines.push('| Source inventory (legacy) | Count |');
  lines.push('|---|---|');
  for (const [k, v] of Object.entries(inv)) lines.push(`| ${k} | ${v === null ? 'n/a' : v} |`);
  lines.push('');
  lines.push(`- travel matrix: \`${provenance.travelStatus ?? 'n/a'}\` — H14 stays UNSUPPORTED, so TRAVEL is not weighted.`);
  lines.push('- H13 transfer: no teacher declares `allowedTransferBranches`, so TRANSFER stays INACTIVE.');
  lines.push('- The input was not mutated between runs; `benchmarkInputHash` is computed from a');
  lines.push('  personal-data-free structural projection, so the same hash proves the same data.');
  return lines;
}

function promptBlock(smoke, quality) {
  const lines = [];
  const model = smoke?.decision?.strategyHash ?? null;
  lines.push(`- Node situation report version: \`${smoke ? 'PHASE_29' : 'n/a'}\``);
  lines.push(`- Python prompt version: \`${quality?.arms?.AIRLLM?.runs?.[0]?.providerProvenance?.promptVersion ?? 'not reported'}\``);
  lines.push(`- Decision hash from the smoke run: \`${model ?? 'n/a'}\``);
  lines.push('');
  lines.push('If the prompt template changes, bump `AI_STRATEGY_PROMPT_VERSION` and re-run. Results from');
  lines.push('different prompt versions are not comparable and must not be merged.');
  return lines;
}

function runtimeBlock(smoke) {
  if (!smoke) return ['Tier A was not run.', ''];
  const lines = [`**Result: ${smoke.result}**`, ''];
  lines.push('| Step | OK | Detail |');
  lines.push('|---|---|---|');
  for (const s of smoke.steps ?? []) {
    lines.push(`| ${s.name} | ${s.ok ? 'yes' : 'no'} | ${escapeCell(s.detail)} |`);
  }
  lines.push('');
  lines.push(`- \`modelReady\`: \`${smoke.modelReady}\``);
  lines.push(`- \`fallbackUsed\`: \`${smoke.decision ? smoke.decision.fallbackUsed : 'n/a'}\``);
  lines.push(`- Root cause: ${smoke.rootCause ?? 'none — the runtime worked'}`);
  lines.push('');
  const gen = smoke.generation;
  if (gen) {
    lines.push('### Generation settings (brief §10)');
    lines.push('');
    lines.push(...kvTable([
      ['temperature', gen.temperature],
      ['topP', gen.topP],
      ['maxTokens', gen.maxTokens],
      ['seed', gen.seed],
    ]));
    lines.push('');
    lines.push(`- **Determinism: ${smoke.determinism?.guaranteed ? 'guaranteed' : 'NOT guaranteed'}.** ${smoke.determinism?.reason ?? ''}`);
  }
  return lines;
}

/** Every arm-reading section shares this guard. */
function armsOf(quality) {
  return quality?.arms ?? null;
}

function qualityBlock(quality, build) {
  // A caller may hand the renderer a result that carries a conclusion
  // and no per-arm data — test 24b does exactly that. Refusing to
  // render would be the wrong response: the refusal that matters is
  // on the CONCLUSION vocabulary, and losing the whole report to a
  // missing arm table would be a renderer bug, not a safety property.
  if (!quality) return ['Not measured — Tier B did not run.', ''];
  if (!armsOf(quality)) return ['Not measured — this result carries no per-arm data.', ''];
  return build();
}

function validityBlock(quality) {
  return qualityBlock(quality, () => {
  const ai = quality.arms[BENCHMARK_ARMS.AI]?.rates ?? {};
  const base = quality.arms[BENCHMARK_ARMS.BASELINE]?.rates ?? {};
  const lines = ['| Arm | AI requests | valid | fallback | invalid | validityRate | fallbackRate |'];
  lines.push('|---|---|---|---|---|---|---|');
  lines.push(`| DETERMINISTIC_FALLBACK | ${base.requests} | ${base.valid} | ${base.fallback} | ${base.invalid} | ${pct(base.validityRate)} | ${pct(base.fallbackRate)} |`);
  lines.push(`| AIRLLM | ${ai.requests} | ${ai.valid} | ${ai.fallback} | ${ai.invalid} | ${pct(ai.validityRate)} | ${pct(ai.fallbackRate)} |`);
  lines.push('');
  lines.push('"AI requests" counts runs that actually consulted a provider. The baseline consults none');
  lines.push('by construction, so its `0` is a fact about the design and not a 0% success rate.');
  lines.push('');
  lines.push('A run that fell back contributed no AI decision and is excluded from the AI arm\'s score');
  lines.push('distribution. It is counted here, never scored as if it had been an AI run (brief §6, §15).');
  const excluded = quality.arms[BENCHMARK_ARMS.AI]?.excludedFromQuality ?? 0;
  if (excluded > 0) {
    lines.push('');
    lines.push(`**${excluded} run(s) excluded from the AirLLM quality distribution** because they produced no AI decision.`);
  }
  const d = quality.arms[BENCHMARK_ARMS.AI]?.diversity;
  if (d) {
    lines.push('');
    lines.push('### Decision diversity (brief §12, §16)');
    lines.push('');
    lines.push(`- distinct strategy hashes: **${d.distinctStrategyHashes}** of ${d.runs} runs`);
    lines.push(`- distinct optimization modes: ${d.distinctModes} — ${d.modes.map((m) => `\`${m}\``).join(', ') || 'none'}`);
    lines.push(`- distinct candidate counts: ${d.distinctCandidateCounts} — ${d.candidateCounts.join(', ') || 'none'}`);
    lines.push(`- stable across runs: **${d.stable ? 'yes' : 'no'}** (not a defect when sampling is on)`);
  }
  return lines;
  });
}

function fallbackBlock(quality) {
  return qualityBlock(quality, () => {
  const ai = quality.arms[BENCHMARK_ARMS.AI]?.rates ?? {};
  const f = quality.arms[BENCHMARK_ARMS.AI]?.failures ?? {};
  const lines = [
    `\`validAIResponses / totalAIRequests\` = **${ai.valid} / ${ai.requests}** = ${pct(ai.validityRate)}`,
    '',
    `\`fallbackRate\` = **${pct(ai.fallbackRate)}**`,
    '',
  ];
  if (f.SERVICE_UNREACHABLE || f.MODEL_LOAD_FAILURE || f.MODEL_NOT_READY) {
    lines.push('The service being unavailable is **not** the same as a model being wrong. Those are');
    lines.push('counted separately below (brief §29, §30) and both are reported as fallbacks, because both');
    lines.push('produce a valid schedule.');
  }
  return lines;
  });
}

function armBlock(quality, arm) {
  return qualityBlock(quality, () => {
  const a = quality.arms[arm];
  if (!a) return ['Not measured.', ''];
  const armName = arm === BENCHMARK_ARMS.AI ? 'the AirLLM' : 'the baseline';
  const lines = [`**n = ${a.runCount} runs, ${a.scoredRunCount} of them contributing a strategy to `
    + `${armName} arm's quality distribution.**`, ''];

  lines.push('| Metric | n | mean | median | min | max | stdev | values |');
  lines.push('|---|---|---|---|---|---|---|---|');
  for (const name of QUALITY_METRIC_NAMES) {
    const d = a.quality[name];
    if (!d) continue;
    lines.push(`| ${name} | ${d.n} | ${num(d.mean)} | ${num(d.median)} | ${num(d.min)} | ${num(d.max)} | ${num(d.stdev)} | ${list(d.values)} |`);
  }
  lines.push('');
  lines.push(`- runs with hard violations: **${a.feasibility.runsWithHardViolations}** (the gate is 0)`);
  lines.push(`- runs that produced an accepted schedule: **${a.feasibility.acceptedCount} / ${a.runCount}**`);
  lines.push(`- independent-evaluator disagreements: **${a.feasibility.oracleDisagreements}**`);
  lines.push(`- every fallback run still hard-feasible (brief §24): **${yesNo(a.feasibility.fallbackRunsHardFeasible)}**`);
  lines.push('');
  if (a.excludedFromQuality > 0) {
    lines.push(`The per-run table below lists all ${a.runCount} runs, including the ${a.excludedFromQuality} that`);
    lines.push('contributed no strategy and therefore no score. Their metrics are still real measurements of');
    lines.push('the pipeline\'s behaviour, and the summary table above deliberately excludes them.');
  }

  if (a.runs?.length) {
    lines.push('');
    lines.push('| run | strategyHash | mode | candidateCount | fallbackUsed | accepted | bestGlobalScore |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const r of a.runs) {
      lines.push(
        `| ${r.index} | \`${r.strategyHash ?? 'n/a'}\` | \`${r.decision?.optimizationMode ?? 'n/a'}\` `
        + `| ${r.decision?.candidateCount ?? 'n/a'} | ${r.fallbackUsed} | ${r.accepted} | ${num(r.quality?.bestGlobalScore)} |`,
      );
    }
  }
  return lines;
  });
}

function comparisonBlock(quality) {
  if (!quality) return ['Not measured — Tier B did not run.', ''];
  const c = quality.comparison;
  if (!c) return ['Not measured — this result carries no comparison.', ''];
  const lines = [];
  lines.push(`- **Verdict: \`${c.verdict}\`** on \`${c.primaryMetric}\``);
  lines.push(`- **Separation: \`${c.separation}\`** — median delta ${num(c.medianDelta)}`);
  lines.push(`- ${c.note}`);
  lines.push('');

  const spc = quality.sharedPoolComparison;
  if (spc) {
    lines.push('### The same comparison on a common scale');
    lines.push('');
    lines.push(`- **Verdict: \`${spc.verdict}\`** on \`${spc.primaryMetric}\``);
    lines.push(`- **Separation: \`${spc.separation}\`** — median delta ${num(spc.medianDelta)}`);
    lines.push('');
    lines.push('`bestGlobalScore` is a position inside that run\'s own candidate pool;');
    lines.push('`sharedPoolGlobalScore` is a position inside one pool holding every arm\'s shipped schedule.');
    lines.push('The policy decides on the first, and this line exists so a reader is not left with only the');
    lines.push('flattering one. If the two verdicts contradict, the benchmark claims no direction at all.');
  }
  lines.push('');

  const f = quality.fairness;
  lines.push('### Fair comparison (brief §4, §19)');
  lines.push('');
  // `kvTable` returns an array of lines, so it must be SPREAD into
  // `out`/`lines`. Pushing it unspread puts a single comma-joined
  // element in the output — a real bug this comment now prevents a
  // second occurrence of.
  lines.push(...kvTable([
    ['solver profile hash', f.solverProfileHash],
    ['seed', f.solverProfile.seed],
    ['per-solve budget', `${f.solverProfile.perSolveTimeBudgetMs} ms`],
    ['overall budget', `${f.solverProfile.overallTimeBudgetMs} ms`],
    ['fair candidateCount', f.candidateCount],
    ['baseline natural counts', f.naturalCandidateCounts.BASELINE.join(', ') || 'n/a'],
    ['AirLLM natural counts', f.naturalCandidateCounts.AIRLLM.join(', ') || 'n/a'],
    ['baseline raised to the fair count', yesNo(f.raisedBaselineToFairCount)],
    ['respectStrategyMode', yesNo(f.solverProfile.respectStrategyMode)],
  ]));
  lines.push('');
  lines.push('The only thing that differed between the two arms: **strategy source**. Same input, seed,');
  lines.push('solver, evaluator, scorer, time budget, and candidate count.');
  lines.push('');
  lines.push(...kvTable([
    ['baseline repetitions', quality.fairness.baselineRepetitions],
    ['AirLLM repetitions', quality.fairness.airllmRepetitions],
    ['AirLLM repetitions reduced', yesNo(quality.fairness.airllmRepetitionsReduced)],
  ]));
  lines.push('');
  if (quality.fairness.airllmRepetitionsReduced) {
    lines.push(`> ${quality.fairness.airllmRepetitionsReason}`);
    lines.push('');
  }

  const sp = quality.sharedPool;
  if (sp) {
    lines.push('### Shared-pool re-scoring');
    lines.push('');
    lines.push(...kvTable([
      ['candidates in the shared pool', sp.poolSize],
      ['scored', sp.scored],
      ['runs with no schedule to score', sp.unscoreable],
    ]));
    lines.push('');
    lines.push(sp.scaleNote);
    lines.push('');
    lines.push('`sharedPoolGlobalScore` uses the scorer\'s own default weights, not either arm\'s');
    lines.push('strategy weights. The AI\'s weights are a legitimate part of its strategy, but they are');
    lines.push('not the yardstick — one fixed yardstick is applied to both arms\' shipped schedules.');
    lines.push('');

    // A pool where every candidate is the same schedule has no spread
    // to normalise against, so every dimension collapses to the
    // neutral 0.5 and every candidate scores 0.5. That is correct,
    // but a reader who sees "0.5000" five times deserves to be told
    // why rather than left to guess whether the metric is broken.
    const shared = Object.values(quality.arms ?? {})
      .flatMap((a) => (a?.runs ?? []).map((r) => r?.quality?.sharedPoolGlobalScore))
      .filter((v) => typeof v === 'number');
    const distinct = [...new Set(shared)];
    if (shared.length > 1 && distinct.length === 1) {
      lines.push('> **This shared pool is degenerate.** Every run shipped the same schedule, so there is');
      lines.push('> no spread to normalize against: every dimension collapses to the neutral `0.5` and');
      lines.push('> every candidate scores `0.5`. The number is correct and it says nothing either way —');
      lines.push('> a pool needs at least two distinct schedules to discriminate.');
      lines.push('');
    }
  }

  const de = quality.decisionEffect;
  lines.push('### Strategy-only effect (brief §20)');
  lines.push('');
  lines.push(`- baseline strategy hashes: ${de.baselineHashes.map((h) => `\`${h}\``).join(', ') || 'none'}`);
  lines.push(`- AirLLM strategy hashes: ${de.aiHashes.map((h) => `\`${h}\``).join(', ') || 'none'}`);
  lines.push(`- **${de.signal}**`);
  lines.push('');
  lines.push(de.note);
  lines.push('');

  lines.push('### Per-run (no cherry-picking, brief §22, §23)');
  lines.push('');
  const bCount = quality.arms?.[BENCHMARK_ARMS.BASELINE]?.runCount ?? 0;
  const aCount = quality.arms?.[BENCHMARK_ARMS.AI]?.runCount ?? 0;
  if (bCount !== aCount) {
    lines.push(`The arms ran a different number of times (baseline ${bCount}, AirLLM ${aCount}), so the`);
    lines.push('table below has one row per run of the longer arm and `n/a` where the other arm has no');
    lines.push('counterpart. Both counts are reported rather than trimmed to the shorter one.');
    lines.push('');
  }
  lines.push('| # | baseline bestGlobalScore | AirLLM bestGlobalScore | delta | baseline spread | AirLLM spread | baseline maxLoad | AirLLM maxLoad | baseline stdev | AirLLM stdev |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const r of c.perRun) {
    const b = r.quality.BASELINE;
    const a = r.quality.AIRLLM;
    lines.push(
      `| ${r.index} | ${num(r.baseline)} | ${num(r.airllm)} | ${num(r.delta)} `
      + `| ${num(b?.bestWorkloadSpread)} | ${num(a?.bestWorkloadSpread)} `
      + `| ${num(b?.bestMaxTeacherLoad)} | ${num(a?.bestMaxTeacherLoad)} `
      + `| ${num(b?.bestWorkloadStdev)} | ${num(a?.bestWorkloadStdev)} |`,
    );
  }
  return lines;
}

function latencyBlock(quality) {
  return qualityBlock(quality, () => {
  const base = quality.arms[BENCHMARK_ARMS.BASELINE]?.latency ?? {};
  const ai = quality.arms[BENCHMARK_ARMS.AI]?.latency ?? {};
  const lines = ['| Stage | baseline median | AirLLM median | AirLLM mean | AirLLM max |', '|---|---|---|---|---|'];
  for (const name of LATENCY_METRIC_NAMES) {
    lines.push(`| ${name} | ${num(base[name]?.median)} | ${num(ai[name]?.median)} | ${num(ai[name]?.mean)} | ${num(ai[name]?.max)} |`);
  }
  lines.push('');
  lines.push('All values in milliseconds. `aiLatencyMs` is the provider round trip as the orchestrator');
  lines.push('measured it. The AI call is outside the solver\'s budget, so the two arms each received a');
  lines.push('full solver budget of their own and neither was charged for the other\'s latency.');
  return lines;
  });
}

function failureBlock(quality) {
  return qualityBlock(quality, () => {
  const ai = quality.arms[BENCHMARK_ARMS.AI]?.failures ?? {};
  const lines = ['| Failure class | AirLLM runs |', '|---|---|'];
  for (const c of ALL_AIRLLM_FAILURES) lines.push(`| ${c} | ${ai[c] ?? 0} |`);
  lines.push(`| NONE | ${ai.NONE ?? 0} |`);
  lines.push('');
  lines.push('These are kept apart on purpose. A dead service, a model that will not load, a model that');
  lines.push('returned malformed JSON, a decision the validator refused, and a strategy that led the');
  lines.push('solver nowhere all have different fixes. They are never reported as one `AI_ERROR`.');
  lines.push('');
  const details = (quality.arms[BENCHMARK_ARMS.AI]?.runs ?? [])
    .filter((r) => r.failure?.class)
    .map((r) => `- run ${r.index}: \`${r.failure.class}\` — ${r.failure.detail ?? r.failure.code}`);
  if (details.length) {
    lines.push('Per-run detail:');
    lines.push(...details);
  }
  return lines;
  });
}

function conclusionBlock(quality) {
  const lines = [];

  // PHASE 35. Tier B did not run. Say exactly that.
  //
  // This used to fall through to `AIRLLM_BENCHMARK_BLOCKED` and then
  // dereference `quality.conclusionReason`, which crashed the CLI on a
  // documented flag. The default was also the wrong answer: a Tier-A
  // run that reached AIRLLM_RUNTIME_READY has not been blocked, it has
  // simply not been asked the quality question. A blocked benchmark and
  // a skipped one are different facts and must not share a verdict.
  if (!quality) {
    lines.push('### Tier B was not run');
    lines.push('');
    lines.push(
      'No strategy-quality comparison was made, so **no quality claim is made in '
        + 'either direction**. The runtime result above stands on its own; a '
        + 'runtime that loaded a model and produced a decision is evidence about '
        + 'the runtime, and says nothing about whether the decision improves a '
        + 'schedule over the deterministic fallback.',
    );
    return lines;
  }

  const conclusion = quality.conclusion ?? 'AIRLLM_BENCHMARK_BLOCKED';
  // A guard, not a formality: the renderer must not be able to print a
  // conclusion outside the five allowed values even if a caller hands
  // it one.
  if (!ALLOWED_CONCLUSIONS.includes(conclusion)) {
    lines.push(`**RENDERER REFUSED: \`${conclusion}\` is not one of the five permitted conclusions.**`);
    lines.push('');
    lines.push('Permitted:');
    for (const c of ALLOWED_CONCLUSIONS) lines.push(`- \`${c}\``);
    return lines;
  }

  lines.push(`### ${conclusion}`);
  lines.push('');
  lines.push(quality.conclusionReason ?? '');
  lines.push('');

  const c = quality?.comparison;
  if (c) {
    lines.push('| Quantity | Value |');
    lines.push('|---|---|');
    // `arms` is optional-chained: the renderer must survive a result
    // that carries a conclusion but no per-arm data, because refusing
    // to render is not the same as refusing to render an out-of-
    // vocabulary conclusion.
    const b = quality.arms?.[BENCHMARK_ARMS.BASELINE]?.quality ?? {};
    const a = quality.arms?.[BENCHMARK_ARMS.AI]?.quality ?? {};
    lines.push(`| per-run verdict | \`${c.verdict}\` |`);
    lines.push(`| separation | \`${c.separation}\` |`);
    for (const name of QUALITY_METRIC_NAMES) {
      lines.push(`| baseline ${name} (median) | ${num(b[name]?.median)} |`);
      lines.push(`| AirLLM ${name} (median) | ${num(a[name]?.median)} |`);
    }
  }
  lines.push('');
  lines.push('### What this phase does NOT establish');
  lines.push('');
  lines.push('- Whether an instruct model was used. The harness records `UNVERIFIED`; nothing `/health`');
  lines.push('  reports can distinguish an instruct checkpoint from a base one.');
  lines.push('- Whether the parser is at fault when output is malformed. The parser is never relaxed to');
  lines.push('  make a number look better (brief §9).');
  lines.push('- Any quality claim beyond the metric named in the policy, and beyond this repetition count.');
  return lines;
}

